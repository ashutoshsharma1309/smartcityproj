"""phase 2: cities, hydrology, civic incidents, multi-city keys

Revision ID: 0003
Revises: 0002
Create Date: 2026-08-08

Adds the Phase 2 data model:

* ``cities`` — the platform stops being single-city configuration and becomes
  multi-tenant by row. Every spatial table gains a ``city_id``.
* ``waterbodies``, ``elevation_points``, ``civic_incidents``.
* ``flood_incidents.occurred_on`` becomes nullable and gains ``record_type``,
  because the largest Chennai flood layer records *where* inundation happens
  with a measured depth but carries no date. Forcing a date would mean
  inventing one.
* ``road_segments.osm_id`` becomes ``external_id``: roads now arrive from two
  sources (GCC centrelines and OpenStreetMap), so the identifier cannot be
  OSM-specific.
* ``ingestion_runs`` gains the full validation-report columns, so data-quality
  scores are computed from the run that produced the data rather than tracked
  separately.

Column drops on ``road_segments`` are safe here: all spatial tables were empty
when this revision was authored (Phase 1 ingested no data).
"""

